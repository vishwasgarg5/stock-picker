"""Weekend data integrity audit with source-backed OHLCV refresh.

Only market bars are automatically repaired, using the repository's existing
Yahoo Finance downloader and ticker mapping. Derived predictions/model artifacts
are audited but never imputed: they must be regenerated by their owning pipeline.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
REPORT_JSON = DATA / "weekend_data_quality_audit.json"
REPORT_CSV = DATA / "weekend_data_quality_audit.csv"

MODEL_KEYWORDS = (
    "prediction", "candidate", "ranking", "confidence", "model", "forecast",
    "validation", "evaluation", "governance", "calibration", "performance",
    "regime", "feature", "selection", "direction", "strategy",
)


def _is_model_artifact(path: Path) -> bool:
    name = path.name.lower()
    return any(token in name for token in MODEL_KEYWORDS) or path.parent.name.lower() == "models"


def _audit_csv(path: Path) -> dict[str, Any]:
    try:
        frame = pd.read_csv(path, low_memory=False)
    except Exception as exc:
        return {"file": str(path.relative_to(ROOT)), "type": "csv", "status": "UNREADABLE",
                "error": str(exc), "rows": None, "columns": None,
                "missing_cells": None, "duplicate_rows": None}
    missing_by_column = {
        str(column): int(count)
        for column, count in frame.isna().sum().items() if int(count) > 0
    }
    non_finite: dict[str, int] = {}
    for column in frame.select_dtypes(include=[np.number]).columns:
        values = pd.to_numeric(frame[column], errors="coerce")
        count = int((~np.isfinite(values.dropna())).sum())
        if count:
            non_finite[str(column)] = count
    return {
        "file": str(path.relative_to(ROOT)), "type": "csv",
        "scope": "MODEL" if _is_model_artifact(path) else "COLLECTED_DATA",
        "status": "ISSUES_FOUND" if missing_by_column or non_finite else "PASS",
        "rows": int(len(frame)), "columns": int(len(frame.columns)),
        "missing_cells": int(frame.isna().sum().sum()),
        "missing_by_column": missing_by_column,
        "non_finite_by_column": non_finite,
        "duplicate_rows": int(frame.duplicated().sum()),
    }


def _audit_json(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        return {"file": str(path.relative_to(ROOT)), "type": "json", "status": "UNREADABLE",
                "error": str(exc)}
    def count_missing(value: Any) -> int:
        if value is None:
            return 1
        if isinstance(value, float) and not np.isfinite(value):
            return 1
        if isinstance(value, dict):
            return sum(count_missing(v) for v in value.values())
        if isinstance(value, list):
            return sum(count_missing(v) for v in value)
        return 0
    missing = count_missing(payload)
    return {"file": str(path.relative_to(ROOT)), "type": "json",
            "scope": "MODEL" if _is_model_artifact(path) else "COLLECTED_DATA",
            "status": "ISSUES_FOUND" if missing else "PASS",
            "missing_values": int(missing)}


def refresh_market_history() -> dict[str, Any]:
    """Use the same Yahoo source and corporate-action-safe merger as daily pipeline."""
    from .pipeline import (
        UNIVERSE_FILE, update_history, update_fundamentals,
        record_fundamentals_snapshot, HISTORY_FILE, validate_data_quality,
    )

    if not UNIVERSE_FILE.exists():
        raise RuntimeError("data/universe.csv is missing; cannot safely refresh market history")
    universe = pd.read_csv(UNIVERSE_FILE)
    if "symbol" not in universe:
        raise RuntimeError("data/universe.csv has no symbol column")
    symbols = universe["symbol"].dropna().astype(str).str.upper().str.strip()
    symbols = [s for s in symbols.unique().tolist() if s and not s.startswith("DUMMY")]
    if not symbols:
        raise RuntimeError("Universe contains no valid symbols")
    before = pd.read_csv(HISTORY_FILE) if HISTORY_FILE.exists() else pd.DataFrame()
    refreshed = update_history(symbols)
    # A non-empty partial download is not sufficient: require the same clean,
    # completed-session coverage gate used by the production prediction path.
    quality = validate_data_quality(refreshed, symbols, context="weekend audit")
    fundamentals = update_fundamentals(symbols)
    latest_market_date = pd.to_datetime(refreshed["date"], errors="coerce").max() if not refreshed.empty else pd.NaT
    if pd.notna(latest_market_date):
        record_fundamentals_snapshot(fundamentals, latest_market_date)
    return {
        "symbols_requested": len(symbols),
        "rows_before": int(len(before)),
        "rows_after": int(len(refreshed)),
        "rows_added_or_refreshed": int(max(0, len(refreshed) - len(before))),
        "latest_completed_session": str(pd.Timestamp(quality["latest_date"]).date()),
        "latest_session_fresh_symbols": int(quality["fresh_symbols"]),
        "latest_session_coverage_pct": round(float(quality["coverage"]) * 100.0, 2),
        "fundamental_symbols_refreshed": int(len(fundamentals)),
        "fundamentals_source": "Yahoo Finance via src.pipeline.update_fundamentals",
        "source": "Yahoo Finance via src.pipeline.update_history",
        "status": "PASS" if not refreshed.empty and len(fundamentals) == len(symbols) else "FAILED",
    }


def run() -> dict[str, Any]:
    DATA.mkdir(exist_ok=True)
    market_refresh = refresh_market_history()
    from .historical_coverage_audit import run as run_historical_coverage_audit
    historical_coverage = run_historical_coverage_audit()
    records: list[dict[str, Any]] = []
    audit_roots = [DATA, ROOT / "models"]
    for audit_root in audit_roots:
        if not audit_root.exists():
            continue
        for path in sorted(audit_root.rglob("*")):
            if not path.is_file() or path in {REPORT_JSON, REPORT_CSV}:
                continue
            if path.suffix.lower() == ".csv":
                records.append(_audit_csv(path))
            elif path.suffix.lower() == ".json":
                records.append(_audit_json(path))

    model_records = [r for r in records if r.get("scope") == "MODEL"]
    issues = [r for r in records if r.get("status") not in {"PASS"}]
    report = {
        "status": "PASS" if not issues and market_refresh["status"] == "PASS" else "REVIEW_REQUIRED",
        "market_data_refresh": market_refresh,
        "historical_coverage": historical_coverage,
        "files_audited": len(records),
        "audit_roots": ["data/", "models/"],
        "model_artifacts_audited": len(model_records),
        "files_with_issues": len(issues),
        "model_artifacts_with_issues": sum(r.get("status") != "PASS" for r in model_records),
        "repair_policy": (
            "Only OHLCV is refreshed from Yahoo Finance. Missing values in predictions, "
            "rankings, confidence, validation and other derived artifacts are reported, "
            "not guessed or imputed; regenerate them through their owning pipeline after "
            "checking upstream inputs."
        ),
        "files": records,
    }
    REPORT_JSON.write_text(json.dumps(report, indent=2, default=str), encoding="utf-8")
    pd.DataFrame(records).to_csv(REPORT_CSV, index=False)
    print(json.dumps(report, indent=2, default=str))
    if market_refresh["status"] != "PASS":
        raise RuntimeError("Weekend market-data refresh failed; see weekend audit report")
    return report


if __name__ == "__main__":
    run()
